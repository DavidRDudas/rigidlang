//! JavaScript backend: lowers a resolved workspace to a single ES module.
//!
//! Design rules:
//!   * Names are mangled from module path + definition name, so two modules
//!     may define the same name without collision. Rigid's identity model
//!     already made names presentation-only; here they are just labels.
//!   * `dyn` sites lower to a membership check + call, preserving the
//!     quarantine at runtime in the emitted code (a violation throws the
//!     same message rigid's VM produces).
//!   * Tables lower to frozen objects; dispatch is a key lookup with the
//!     same closed-set error on a miss.
//!   * `fail`/`try` lower to throw/catch of a RigidError carrying a value.
//!   * Integer division truncates toward zero (Math.trunc) to match rigid.
//!   * Effects (`!io`) are erased: they are a compile-time discipline.

use crate::ast::*;
use crate::resolve::{Binding, DefId, DefKind, Workspace};

pub struct Js<'a> {
    ws: &'a Workspace,
    out: String,
}

fn mangle(module_path: &str, name: &str) -> String {
    let m: String = module_path
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { '_' })
        .collect();
    format!("{}__{}", m.trim_matches('_'), name)
}

const PRELUDE: &str = r#"// generated by rigid — do not edit
//
// rigid has two number domains and JavaScript has one, so the mapping is:
//   rigid Int   -> BigInt   (all 64 bits, exactly)
//   rigid Float -> number   (float64, and free to mean only that)
// A plain JS number would silently round 9007199254740993 and could not tell
// 2 from 2.0. `typeof` tells the two apart at every boundary below.
class RigidError extends Error {
  // $disp, not JSON.stringify: a BigInt has no JSON encoding, and the
  // message has to match what rigid's own engine prints anyway.
  constructor(value) { super(typeof value === "string" ? value : $disp(value)); this.value = value; }
}
const $isint = (v) => typeof v === "bigint";
const $isnum = (v) => typeof v === "bigint" || typeof v === "number";
// Arithmetic on two ints stays exact; a float on either side promotes, which
// is what rigid's own engine does.
const $num = (op, a, b, name) => {
  if (typeof a === "bigint" && typeof b === "bigint") return op(a, b, true);
  if ($isnum(a) && $isnum(b)) return op(Number(a), Number(b), false);
  throw new RigidError("operator needs numbers (got " + $disp(a) + " and " + $disp(b) + ")");
};
const $sub = (a, b) => $num((x, y) => x - y, a, b);
const $mul = (a, b) => $num((x, y) => x * y, a, b);
const $div = (a, b) => $num((x, y, isInt) => {
  if (isInt) { if (y === 0n) throw new RigidError("division by zero"); return x / y; }
  return x / y;
}, a, b);
const $rem = (a, b) => $num((x, y, isInt) => {
  if (isInt && y === 0n) throw new RigidError("remainder by zero");
  return x % y;
}, a, b);
const $add = (a, b) => {
  if (Array.isArray(a) && Array.isArray(b)) return a.concat(b);
  if (typeof a === "string" || typeof b === "string") return "" + $str(a) + $str(b);
  return $num((x, y) => x + y, a, b);
};
const $cmp = (op) => (a, b) => {
  if (typeof a === "string" && typeof b === "string") return op(a, b) ? 1n : 0n;
  if (!$isnum(a) || !$isnum(b)) throw new RigidError("operator needs numbers (got " + $disp(a) + " and " + $disp(b) + ")");
  return op(a, b) ? 1n : 0n;   // BigInt and number compare directly in JS
};
const $lt = $cmp((a, b) => a < b), $gt = $cmp((a, b) => a > b);
const $le = $cmp((a, b) => a <= b), $ge = $cmp((a, b) => a >= b);
// Equality is numeric across the two domains (1 == 1.0) and structural
// otherwise. JSON.stringify cannot see a BigInt, so numbers are keyed by
// their decimal text and floats keep their point.
const $key = (v) => {
  if (typeof v === "bigint") return "n" + v.toString();
  if (typeof v === "number") return "n" + $f(v);
  if (Array.isArray(v)) return "[" + v.map($key).join(",") + "]";
  if (v && typeof v === "object" && typeof v !== "function") return "{" + Object.keys(v).sort().map(k => JSON.stringify(k) + ":" + $key(v[k])).join(",") + "}";
  return JSON.stringify(v);
};
const $eq = (a, b) => {
  if ($isnum(a) && $isnum(b)) return (typeof a === typeof b ? a === b : Number(a) === Number(b)) ? 1n : 0n;
  return $key(a) === $key(b) ? 1n : 0n;
};
const $neg = (v) => { if (!$isnum(v)) throw new RigidError("`-` needs a number"); return -v; };
const $bool = (v) => (v !== 0n && v !== 0 && v !== false);
// The one canonical rendering of a float: shortest round-trip, and a point
// forced onto whole values so 2.0 never reads back as an integer.
const $f = (v) => {
  if (Number.isNaN(v)) return "(0.0 / 0.0)";
  if (!Number.isFinite(v)) return v > 0 ? "(1.0 / 0.0)" : "(-1.0 / 0.0)";
  const s = String(v);
  return (s.includes(".") || s.includes("e")) ? s : s + ".0";
};
const $show = (v) => typeof v === "string" ? v : $disp(v);
const $disp = (v) => {
  if (typeof v === "string") return JSON.stringify(v);
  if (typeof v === "bigint") return v.toString();
  if (typeof v === "number") return $f(v);
  if (typeof v === "function") return "&" + (v.$ref || v.name);
  if (Array.isArray(v)) return "[" + v.map($disp).join(", ") + "]";
  if (v && typeof v === "object") return "{" + Object.keys(v).sort().map(k => k + ": " + $disp(v[k])).join(", ") + "}";
  return String(v);
};
const $print = (v) => { console.log($show(v)); return v; };
const $arity = (f, n, name) => { if (f.length !== n) throw new RigidError((f.$ref || name) + " expects " + f.length + " argument(s), got " + n); return f; };
const $len = (v) => { if (typeof v === "string") return BigInt([...v].length); if (Array.isArray(v)) return BigInt(v.length); throw new RigidError("len needs a list or string, got " + $disp(v)); };
const $push = (xs, v) => { if (!Array.isArray(xs)) throw new RigidError("push needs a list, got " + $disp(xs)); return xs.concat([v]); };
const $ix = (k) => { if (typeof k === "bigint") return Number(k); if (typeof k === "number") return k; return k; };
const $index = (b, k) => {
  const i = $ix(k);
  if (typeof b === "string") { const cs = [...b]; if (i < 0 || i >= cs.length) throw new RigidError("index " + i + " out of bounds (len " + cs.length + ")"); return cs[i]; }
  if (Array.isArray(b)) { if (i < 0 || i >= b.length) throw new RigidError("index " + i + " out of bounds (len " + b.length + ")"); return b[i]; }
  throw new RigidError("cannot index into " + $show(b));
};
const $field = (r, f) => { if (r && typeof r === "object" && !Array.isArray(r)) { if (f in r) return r[f]; throw new RigidError("no field '" + f + "' (fields: " + Object.keys(r).sort().join(", ") + ")"); } throw new RigidError("cannot access field on " + $disp(r)); };
const $int = (s) => {
  if (typeof s === "bigint") return s;
  if (typeof s === "number") return BigInt(Math.trunc(s));   // truncates toward zero
  const t = String(s).trim();
  if (!/^[+-]?[0-9]+$/.test(t)) throw new RigidError("cannot parse " + JSON.stringify(String(s)) + " as an integer");
  return BigInt(t);
};
const $float = (s) => {
  if (typeof s === "number") return s;
  if (typeof s === "bigint") return Number(s);
  const t = String(s).trim();
  const v = Number(t);
  if (t === "" || Number.isNaN(v)) throw new RigidError("cannot parse " + JSON.stringify(String(s)) + " as a float");
  return v;
};
const $str = (v) => {
  if (typeof v === "bigint") return v.toString();
  if (typeof v === "number") return $f(v);
  if (typeof v === "string") return v;
  return $show(v);
};
const $substr = (s, start, count) => { const a = $ix(start), n = $ix(count); const cs = [...String(s)]; if (a < 0 || a > cs.length || n < 0) throw new RigidError("substr out of range (start " + a + ", count " + n + ", len " + cs.length + ")"); return cs.slice(a, a + n).join(""); };
const $chars = (s) => [...String(s)];
// A closure is the lifted definition with its captures already applied. The
// arity and the $ref are preserved so quarantine and arity errors read the
// same as they do for a named reference.
const $close = (f, caught) => {
  const g = (...rest) => f(...caught, ...rest);
  Object.defineProperty(g, "length", { value: Math.max(0, f.length - caught.length) });
  g.$ref = f.$ref; g.$of = f;
  return g;
};
const $seq = (v) => { if (Array.isArray(v)) return v; if (typeof v === "string") return [...v]; throw new RigidError("`for` needs a list or string, got " + $disp(v)); };
const $join = (xs, sep) => xs.map($str).join(sep);
const $try = (thunk) => { try { return { ok: 1n, value: thunk() }; } catch (e) { if (e instanceof RigidError) return { ok: 0n, error: e.value }; throw e; } };
const $fail = (v) => { throw new RigidError(v); };
const $dyn = (f, set, names) => { if (!set.includes(f) && !set.includes(f.$of)) throw new RigidError("quarantine violation: &" + (f.$ref || f.name) + " is not in the declared set { " + names.join(", ") + " }"); return f; };
// Rigid values crossing *out* to a host function. Host code expects plain
// numbers, so an Int is narrowed — but only when it survives the trip.
// Above 2^53 a float64 cannot represent it, and handing over a wrong number
// silently is the exact failure this backend just stopped committing.
const $out = (v, name) => {
  if (typeof v === "bigint") {
    if (v > 9007199254740991n || v < -9007199254740991n)
      throw new RigidError("extern '" + name + "' was passed " + v.toString() + ", which a JavaScript number cannot represent exactly");
    return Number(v);
  }
  if (Array.isArray(v)) return v.map((x) => $out(x, name));
  if (v !== null && typeof v === "object" && typeof v !== "function") {
    const o = {}; for (const k of Object.keys(v)) o[k] = $out(v[k], name); return o;
  }
  return v;
};
// Host values crossing into rigid. A whole JS number becomes an Int and a
// fractional one a Float — now that both exist, neither has to be refused.
const $ffi = (v, name) => {
  const chk = (x) => {
    if (typeof x === "bigint") return x;
    if (typeof x === "number") { if (!Number.isFinite(x)) throw new RigidError("extern '" + name + "' returned " + String(x)); return Number.isInteger(x) ? BigInt(x) : x; }
    if (typeof x === "string") return x;
    if (typeof x === "boolean") return x ? 1n : 0n;  // documented coercion
    if (Array.isArray(x)) return x.map(chk);
    if (x !== null && typeof x === "object" && (Object.getPrototypeOf(x) === Object.prototype || Object.getPrototypeOf(x) === null)) {
      const o = {}; for (const k of Object.keys(x)) o[k] = chk(x[k]); return o;
    }
    throw new RigidError("extern '" + name + "' returned a value outside rigid's domain: " + String(x));
  };
  return chk(v);
};
const $tbl = (t, k, name) => { if (!(k in t)) throw new RigidError("no entry " + JSON.stringify(k) + " in table '" + name + "' (keys: " + Object.keys(t).sort().join(", ") + ")"); return t[k]; };
const $readFile = (p) => { try { return require("fs").readFileSync(p, "utf8"); } catch (e) { throw new RigidError("read_file " + JSON.stringify(p) + ": " + e.message); } };
const $writeFile = (p, v) => { try { require("fs").writeFileSync(p, typeof v === "string" ? v : $show(v)); return v; } catch (e) { throw new RigidError("write_file " + JSON.stringify(p) + ": " + e.message); } };
const $input = () => { try { const b = require("fs").readFileSync(0, "utf8").split("\n"); return b[($input.n = ($input.n || 0)) < b.length ? $input.n++ : b.length - 1]; } catch (e) { return ""; } };
"#;

impl<'a> Js<'a> {
    pub fn emit(ws: &'a Workspace) -> String {
        let mut j = Js {
            ws,
            out: String::new(),
        };
        j.out.push_str(PRELUDE);
        j.out.push('\n');

        // tables first (they are values referenced by functions)
        for d in 0..ws.defs.len() {
            if ws.defs[d].kind != DefKind::Table {
                continue;
            }
            let info = &ws.defs[d];
            let entries = ws.table_entries.get(&d).cloned().unwrap_or_default();
            let body: Vec<String> = entries
                .iter()
                .map(|(k, t)| {
                    format!(
                        "  {}: {}",
                        serde_json::to_string(k).unwrap(),
                        mangle(&ws.defs[*t].module_path, &ws.defs[*t].name)
                    )
                })
                .collect();
            j.out.push_str(&format!(
                "const {} = Object.freeze({{\n{}\n}});\n",
                mangle(&info.module_path, &info.name),
                body.join(",\n")
            ));
        }
        j.out.push('\n');

        for d in 0..ws.defs.len() {
            match ws.defs[d].kind {
                DefKind::Fn => j.func(d),
                DefKind::Extern => j.ext(d),
                DefKind::Table => {}
            }
        }
        for d in 0..ws.defs.len() {
            if ws.defs[d].kind == DefKind::Fn {
                j.memo_wrap(d);
            }
        }

        // qualified reference tags, so runtime messages match rigid's
        for d in 0..ws.defs.len() {
            if ws.defs[d].kind == DefKind::Table {
                continue;
            }
            let info = &ws.defs[d];
            j.out.push_str(&format!(
                "{}.$ref = {};\n",
                mangle(&info.module_path, &info.name),
                serde_json::to_string(&format!("{}#{}", info.module_path, info.name)).unwrap()
            ));
        }

        // CommonJS + ESM friendly export of every definition
        let names: Vec<String> = (0..ws.defs.len())
            .map(|d| mangle(&ws.defs[d].module_path, &ws.defs[d].name))
            .collect();
        j.out.push_str(&format!(
            "\nconst $exports = {{ {} }};\nif (typeof module !== \"undefined\") module.exports = $exports;\n",
            names.join(", ")
        ));
        // CLI entry: node out.js <module#name> args...
        j.out.push_str(
            r##"
if (typeof require !== "undefined" && require.main === module) {
  const [ref, ...args] = process.argv.slice(2);
  if (!ref) { console.error("usage: node <file>.js <module.rg#name> [args...]"); process.exit(1); }
  const want = ref.split("#").pop();
  const f = $exports[Object.keys($exports).find(k => k.endsWith("__" + want))];
  if (!f) { console.error("no such definition: " + ref); process.exit(1); }
  const conv = (a) => /^-?[0-9]+$/.test(a) ? BigInt(a) : (/^-?[0-9]*\.[0-9]+$/.test(a) ? Number(a) : a);
  try { $arity(f, args.length, want); const r = f(...args.map(conv)); console.log($disp(r)); }
  catch (e) { console.error("runtime error: " + (e instanceof RigidError ? $disp(e.value) : e.message)); process.exit(1); }
}
"##,
        );
        j.out
    }

    fn ext(&mut self, d: DefId) {
        let info = &self.ws.defs[d];
        let x = &self.ws.modules[info.module_idx].externs[info.item_idx];
        // host must be a dotted identifier path; anything else is refused at
        // build time rather than emitted as executable text
        let ok = !x.host.is_empty()
            && x.host.split('.').all(|seg| {
                !seg.is_empty()
                    && seg
                        .chars()
                        .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
                    && !seg.chars().next().unwrap().is_ascii_digit()
            });
        let params: Vec<String> = (0..x.params.len()).map(|i| format!("a{}", i)).collect();
        if ok {
            self.out.push_str(&format!(
                "function {}({}) {{ return $ffi({}({}), {}); }}\n",
                mangle(&info.module_path, &info.name),
                params.join(", "),
                x.host,
                params
                    .iter()
                    .map(|a| format!(
                        "$out({}, {})",
                        a,
                        serde_json::to_string(&info.name).unwrap()
                    ))
                    .collect::<Vec<_>>()
                    .join(", "),
                serde_json::to_string(&info.name).unwrap()
            ));
        } else {
            self.out.push_str(&format!(
                "function {}() {{ throw new RigidError(\"extern '{}' has an invalid host path: {}\"); }}\n",
                mangle(&info.module_path, &info.name),
                info.name,
                serde_json::to_string(&x.host).unwrap().replace('"', "'")
            ));
        }
    }

    fn memo_wrap(&mut self, d: DefId) {
        let info = &self.ws.defs[d];
        let f = &self.ws.modules[info.module_idx].fns[info.item_idx];
        if !f.memo {
            return;
        }
        let m = mangle(&info.module_path, &info.name);
        self.out.push_str(&format!(
            "{{ const $inner = {m}; const $c = new Map(); {m} = (...a) => {{ const k = JSON.stringify(a); if ($c.has(k)) return $c.get(k); const v = $inner(...a); $c.set(k, v); return v; }}; }}\n",
            m = m
        ));
    }

    fn func(&mut self, d: DefId) {
        let info = &self.ws.defs[d];
        let f = &self.ws.modules[info.module_idx].fns[info.item_idx];
        let params: Vec<String> = f.params.iter().map(|p| format!("v{}", p.name)).collect();
        self.out.push_str(&format!(
            "function {}({}) {{\n",
            mangle(&info.module_path, &info.name),
            params.join(", ")
        ));
        // locals are slot-based in rigid; declare them lazily by name
        let mut declared: Vec<String> = f.params.iter().map(|p| p.name.clone()).collect();
        let body = self.stmts(d, &f.body, &mut declared, 1);
        self.out.push_str(&body);
        self.out.push_str("}\n\n");
    }

    fn stmts(&self, d: DefId, ss: &[Stmt], declared: &mut Vec<String>, ind: usize) -> String {
        let pad = "  ".repeat(ind);
        let mut out = String::new();
        for s in ss {
            match s {
                Stmt::Let { name, value } => {
                    let v = self.expr(d, value);
                    if declared.contains(&name.name) {
                        out.push_str(&format!("{}v{} = {};\n", pad, name.name, v));
                    } else {
                        declared.push(name.name.clone());
                        out.push_str(&format!("{}let v{} = {};\n", pad, name.name, v));
                    }
                }
                Stmt::Assign { name, value } => {
                    let v = self.expr(d, value);
                    if !declared.contains(&name.name) {
                        declared.push(name.name.clone());
                        out.push_str(&format!("{}let v{} = {};\n", pad, name.name, v));
                    } else {
                        out.push_str(&format!("{}v{} = {};\n", pad, name.name, v));
                    }
                }
                Stmt::Return(e) => {
                    out.push_str(&format!("{}return {};\n", pad, self.expr(d, e)));
                }
                Stmt::Expr(e) => {
                    out.push_str(&format!("{}{};\n", pad, self.expr(d, e)));
                }
                Stmt::IfStmt { cond, then, els } => {
                    out.push_str(&format!("{}if ($bool({})) {{\n", pad, self.expr(d, cond)));
                    out.push_str(&self.stmts(d, then, declared, ind + 1));
                    if els.is_empty() {
                        out.push_str(&format!("{}}}\n", pad));
                    } else {
                        out.push_str(&format!("{}}} else {{\n", pad));
                        out.push_str(&self.stmts(d, els, declared, ind + 1));
                        out.push_str(&format!("{}}}\n", pad));
                    }
                }
                Stmt::For { var, iter, body } => {
                    if !declared.contains(&var.name) {
                        declared.push(var.name.clone());
                    }
                    out.push_str(&format!(
                        "{}for (let v{} of $seq({})) {{\n",
                        pad,
                        var.name,
                        self.expr(d, iter)
                    ));
                    out.push_str(&self.stmts(d, body, declared, ind + 1));
                    out.push_str(&format!("{}}}\n", pad));
                }
                Stmt::While { cond, body } => {
                    out.push_str(&format!("{}while ($bool({})) {{\n", pad, self.expr(d, cond)));
                    out.push_str(&self.stmts(d, body, declared, ind + 1));
                    out.push_str(&format!("{}}}\n", pad));
                }
            }
        }
        out
    }

    fn bind(&self, d: DefId, span: Span, name: &str) -> Binding {
        self.ws
            .bindings
            .get(&(d, span.line, span.col, name.to_string()))
            .copied()
            .unwrap_or(Binding::Broken)
    }

    fn defname(&self, t: DefId) -> String {
        mangle(&self.ws.defs[t].module_path, &self.ws.defs[t].name)
    }

    fn expr(&self, d: DefId, e: &Expr) -> String {
        match e {
            Expr::Int(v) => format!("{}n", v),
            Expr::Float(v) => crate::fmt::fmt_f64(*v),
            Expr::Str(s) => serde_json::to_string(s).unwrap(),
            Expr::Var(id) => match self.bind(d, id.span, &id.name) {
                Binding::Local(_) => format!("v{}", id.name),
                Binding::Def(t) => self.defname(t),
                Binding::Broken => "undefined".to_string(),
            },
            Expr::FunRef(id) => match self.bind(d, id.span, &id.name) {
                Binding::Def(t) => self.defname(t),
                _ => "undefined".to_string(),
            },
            Expr::Lambda {
                lifted, captures, ..
            } => {
                // A closure lowers to a partial application of the lifted
                // definition, so the emitted code carries the same identity
                // the graph does.
                let target = match lifted {
                    Some(id) => match self.bind(d, id.span, &id.name) {
                        Binding::Def(t) => self.defname(t),
                        _ => "undefined".to_string(),
                    },
                    None => "undefined".to_string(),
                };
                let caught: Vec<String> =
                    captures.iter().map(|c| format!("v{}", c.name)).collect();
                if caught.is_empty() {
                    target
                } else {
                    format!("$close({}, [{}])", target, caught.join(", "))
                }
            }
            Expr::TimeCall { .. } => {
                "(()=>{throw new RigidError('temporal calls are VM-only in v14')})()"
                    .to_string()
            }
            Expr::Call { callee, args } => {
                let a: Vec<String> = args.iter().map(|x| self.expr(d, x)).collect();
                match self.bind(d, callee.span, &callee.name) {
                    Binding::Def(t) => format!("{}({})", self.defname(t), a.join(", ")),
                    _ => format!("v{}({})", callee.name, a.join(", ")),
                }
            }
            Expr::DynCall {
                targets,
                callee,
                args,
            } => {
                let set: Vec<String> = targets
                    .iter()
                    .filter_map(|t| match self.bind(d, t.span, &t.name) {
                        Binding::Def(x) => Some(self.defname(x)),
                        _ => None,
                    })
                    .collect();
                let names: Vec<String> = targets
                    .iter()
                    .map(|t| match self.bind(d, t.span, &t.name) {
                        Binding::Def(x) => serde_json::to_string(&format!(
                            "{}#{}",
                            self.ws.defs[x].module_path, self.ws.defs[x].name
                        ))
                        .unwrap(),
                        _ => serde_json::to_string(&t.name).unwrap(),
                    })
                    .collect();
                let a: Vec<String> = args.iter().map(|x| self.expr(d, x)).collect();
                format!(
                    "$dyn({}, [{}], [{}])({})",
                    self.expr(d, callee),
                    set.join(", "),
                    names.join(", "),
                    a.join(", ")
                )
            }
            Expr::TableDispatch { table, key, args } => {
                match self.bind(d, table.span, &table.name) {
                    Binding::Local(_) => {
                        format!("$index(v{}, {})", table.name, self.expr(d, key))
                    }
                    Binding::Def(t) => {
                        let lookup = format!(
                            "$tbl({}, {}, {})",
                            self.defname(t),
                            self.expr(d, key),
                            serde_json::to_string(&self.ws.defs[t].name).unwrap()
                        );
                        match args {
                            None => lookup,
                            Some(a) => {
                                let xs: Vec<String> =
                                    a.iter().map(|x| self.expr(d, x)).collect();
                                format!("{}({})", lookup, xs.join(", "))
                            }
                        }
                    }
                    Binding::Broken => "undefined".to_string(),
                }
            }
            Expr::Binop { op, l, r } => {
                let (a, b) = (self.expr(d, l), self.expr(d, r));
                use BinOp::*;
                match op {
                    Add => format!("$add({}, {})", a, b),
                    Sub => format!("$sub({}, {})", a, b),
                    Mul => format!("$mul({}, {})", a, b),
                    Div => format!("$div({}, {})", a, b),
                    Rem => format!("$rem({}, {})", a, b),
                    Eq => format!("$eq({}, {})", a, b),
                    Ne => format!("(1n - $eq({}, {}))", a, b),
                    Lt => format!("$lt({}, {})", a, b),
                    Gt => format!("$gt({}, {})", a, b),
                    Le => format!("$le({}, {})", a, b),
                    Ge => format!("$ge({}, {})", a, b),
                }
            }
            Expr::If { c, t, e: el } => format!(
                "($bool({}) ? {} : {})",
                self.expr(d, c),
                self.expr(d, t),
                self.expr(d, el)
            ),
            Expr::Neg(x) => format!("$neg({})", self.expr(d, x)),
            Expr::Print { arg, .. } => format!("$print({})", self.expr(d, arg)),
            Expr::Input { .. } => "$input()".to_string(),
            Expr::ListLit(xs) => format!(
                "[{}]",
                xs.iter().map(|x| self.expr(d, x)).collect::<Vec<_>>().join(", ")
            ),
            Expr::RecordLit(fs) => {
                let mut items: Vec<(String, String)> = fs
                    .iter()
                    .map(|(n, v)| (n.name.clone(), self.expr(d, v)))
                    .collect();
                items.sort_by(|a, b| a.0.cmp(&b.0));
                format!(
                    "{{ {} }}",
                    items
                        .iter()
                        .map(|(k, v)| format!("{}: {}", serde_json::to_string(k).unwrap(), v))
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            }
            Expr::Get { base, field } => format!(
                "$field({}, {})",
                self.expr(d, base),
                serde_json::to_string(&field.name).unwrap()
            ),
            Expr::IndexE { base, key } => {
                format!("$index({}, {})", self.expr(d, base), self.expr(d, key))
            }
            Expr::Len(x) => format!("$len({})", self.expr(d, x)),
            Expr::Push(a, b) => format!("$push({}, {})", self.expr(d, a), self.expr(d, b)),
            Expr::StrConv(x) => format!("$str({})", self.expr(d, x)),
            Expr::IntConv(x) => format!("$int({})", self.expr(d, x)),
            Expr::FloatConv(x) => format!("$float({})", self.expr(d, x)),
            Expr::Substr(a, b, c) => format!(
                "$substr({}, {}, {})",
                self.expr(d, a),
                self.expr(d, b),
                self.expr(d, c)
            ),
            Expr::Chars(x) => format!("$chars({})", self.expr(d, x)),
            Expr::Join(a, b) => format!("$join({}, {})", self.expr(d, a), self.expr(d, b)),
            Expr::ReadFile { path, .. } => format!("$readFile({})", self.expr(d, path)),
            Expr::WriteFile { path, contents, .. } => format!(
                "$writeFile({}, {})",
                self.expr(d, path),
                self.expr(d, contents)
            ),
            Expr::Fail(x) => format!("$fail({})", self.expr(d, x)),
            Expr::Try(x) => format!("$try(() => {})", self.expr(d, x)),
        }
    }
}
