impl<'a> Js<'a> {
    pub fn emit(ws: &'a Workspace) -> String {
        let mut slots: HashMap<DefId, u32> = HashMap::new();
        for ((d, _, _, _), b) in &ws.bindings {
            if let Binding::Local(s) = b {
                let e = slots.entry(*d).or_insert(0);
                *e = (*e).max(s + 1);
            }
        }
        let mut j = Js {
            ws,
            out: String::new(),
            slots,
        };
        j.out.push_str(PRELUDE);
        j.out.push_str(&format!(
            "const $DEPTH = {}, $DEPTH_MSG = {};\n\n",
            crate::eval::MAX_CALL_DEPTH,
            js_str(&crate::eval::depth_error())
        ));

        for d in 0..ws.defs.len() {
            match ws.defs[d].kind {
                DefKind::Fn => j.func(d),
                DefKind::Extern => j.ext(d),
                DefKind::Table => {}
            }
        }
        // identities, before anything copies a function value
        for d in 0..ws.defs.len() {
            if ws.defs[d].kind != DefKind::Table {
                j.out.push_str(&format!("{}.$h = {};\n", j.defname(d), js_str(&j.tag(d))));
            }
        }
        for d in 0..ws.defs.len() {
            if ws.defs[d].kind == DefKind::Fn {
                j.memo_wrap(d);
            }
        }
        // tables last, so they hold what a call should reach (a memo
        // wrapper, not the function under it)
        for d in 0..ws.defs.len() {
            if ws.defs[d].kind != DefKind::Table {
                continue;
            }
            let entries = ws.table_entries.get(&d).cloned().unwrap_or_default();
            let body: Vec<String> = entries
                .iter()
                .map(|(k, t)| format!("[{}, {}]", js_str(k), j.defname(*t)))
                .collect();
            let name = j.defname(d);
            j.out.push_str(&format!(
                "const {} = new Map([{}]);\n{}.$h = {};\n",
                name,
                body.join(", "),
                name,
                js_str(&j.tag(d))
            ));
        }

        let byref: Vec<String> = (0..ws.defs.len())
            .map(|d| {
                format!(
                    "{}: {}",
                    js_str(&format!("{}#{}", ws.defs[d].module_path, ws.defs[d].name)),
                    j.defname(d)
                )
            })
            .collect();
        j.out.push_str(&format!("const $byref = {{ {} }};\n", byref.join(", ")));
        // CommonJS + ESM friendly export of every definition, plus `$rigid`:
        // the runtime's own display and error reading, so a host (or a
        // differential test) renders results exactly as `rigid run` does.
        let names: Vec<String> = (0..ws.defs.len()).map(|d| j.defname(d)).collect();
        j.out.push_str(&format!(
            "\nconst $exports = {{ {}{}$rigid: {{ disp: $disp, caught: $caught, byref: $byref }} }};\nif (typeof module !== \"undefined\") module.exports = $exports;\n",
            names.join(", "),
            if names.is_empty() { "" } else { ", " }
        ));
        // CLI entry: node out.js <module#name> args...
        j.out.push_str(CLI);
        j.out
    }

    fn tag(&self, d: DefId) -> String {
        crate::canon::tag(self.ws, d)
    }

    fn ext(&mut self, d: DefId) {
        let info = &self.ws.defs[d];
        let x = &self.ws.modules[info.module_idx].externs[info.item_idx];
        // host must be a dotted identifier path; anything else is refused at
        // build time rather than emitted as executable text
        let ok = !x.host.is_empty()
            && x.host.split('.').all(|seg| {
                !seg.is_empty()
                    && seg
                        .chars()
                        .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
                    && !seg.chars().next().unwrap().is_ascii_digit()
            });
        let params: Vec<String> = (0..x.params.len()).map(|i| format!("a{}", i)).collect();
        // Messages name the host path, which is part of the extern's
        // identity, rather than the rigid name, which is not.
        let host = js_str(&x.host);
        if ok {
            self.out.push_str(&format!(
                "function {}({}) {{ return $ffi({}({}), {}); }}\n",
                self.defname(d),
                params.join(", "),
                x.host,
                params
                    .iter()
                    .map(|a| format!("$out({}, {})", a, host))
                    .collect::<Vec<_>>()
                    .join(", "),
                host
            ));
        } else {
            self.out.push_str(&format!(
                "function {}({}) {{ throw new RigidError({}); }}\n",
                self.defname(d),
                params.join(", "),
                js_str(&format!("extern {} has an invalid host path", x.host))
            ));
        }
    }

    fn memo_wrap(&mut self, d: DefId) {
        let info = &self.ws.defs[d];
        let f = &self.ws.modules[info.module_idx].fns[info.item_idx];
        if f.memo {
            let m = self.defname(d);
            self.out.push_str(&format!("{m} = $memo({m});\n", m = m));
        }
    }

    fn func(&mut self, d: DefId) {
        let info = &self.ws.defs[d];
        let f = &self.ws.modules[info.module_idx].fns[info.item_idx];
        let np = f.params.len() as u32;
        let params: Vec<String> = (0..np).map(|i| format!("s{}", i)).collect();
        let mut s = format!("function {}({}) {{\n", self.defname(d), params.join(", "));
        s.push_str("  if (++$d > $DEPTH) { $d--; throw new RigidError($DEPTH_MSG); }\n  try {\n");
        // every local exists from the start and reads as 0 until assigned,
        // which is the VM's flat per-function scope
        let n = self.slots.get(&d).copied().unwrap_or(0).max(np);
        if n > np {
            let decls: Vec<String> = (np..n).map(|i| format!("s{} = 0n", i)).collect();
            s.push_str(&format!("    let {};\n", decls.join(", ")));
        }
        s.push_str(&self.stmts(d, &f.body, 2));
        s.push_str(&format!(
            "    throw new RigidError({});\n  }} finally {{ $d--; }}\n}}\n\n",
            js_str(&format!("{} finished without `return`", self.tag(d)))
        ));
        self.out.push_str(&s);
    }

    fn slot(&self, d: DefId, id: &Ident) -> String {
        match self.bind(d, id.span, &id.name) {
            Binding::Local(s) => format!("s{}", s),
            _ => "undefined".to_string(),
        }
    }

    fn stmts(&self, d: DefId, ss: &[Stmt], ind: usize) -> String {
        let pad = "  ".repeat(ind);
        let mut out = String::new();
        for s in ss {
            match s {
                Stmt::Let { name, value } | Stmt::Assign { name, value } => {
                    out.push_str(&format!("{}{} = {};\n", pad, self.slot(d, name), self.expr(d, value)));
                }
                Stmt::Return(e) => {
                    out.push_str(&format!("{}return {};\n", pad, self.expr(d, e)));
                }
                Stmt::Expr(e) => {
                    out.push_str(&format!("{}{};\n", pad, self.expr(d, e)));
                }
                Stmt::IfStmt { cond, then, els } => {
                    out.push_str(&format!("{}if ($bool({})) {{\n", pad, self.expr(d, cond)));
                    out.push_str(&self.stmts(d, then, ind + 1));
                    if els.is_empty() {
                        out.push_str(&format!("{}}}\n", pad));
                    } else {
                        out.push_str(&format!("{}}} else {{\n", pad));
                        out.push_str(&self.stmts(d, els, ind + 1));
                        out.push_str(&format!("{}}}\n", pad));
                    }
                }
                Stmt::For { var, iter, body } => {
                    // the loop variable is the function's own slot, so it
                    // keeps its last value after the loop, as in the VM
                    out.push_str(&format!(
                        "{}for ({} of $seq({})) {{\n",
                        pad,
                        self.slot(d, var),
                        self.expr(d, iter)
                    ));
                    out.push_str(&self.stmts(d, body, ind + 1));
                    out.push_str(&format!("{}}}\n", pad));
                }
                Stmt::While { cond, body } => {
                    out.push_str(&format!("{}while ($bool({})) {{\n", pad, self.expr(d, cond)));
                    out.push_str(&self.stmts(d, body, ind + 1));
                    out.push_str(&format!("{}}}\n", pad));
                }
            }
        }
        out
    }

    fn bind(&self, d: DefId, span: Span, name: &str) -> Binding {
        self.ws
            .bindings
            .get(&(d, span.line, span.col, name.to_string()))
            .copied()
            .unwrap_or(Binding::Broken)
    }

    fn defname(&self, t: DefId) -> String {
        mangle(&self.ws.defs[t].module_path, &self.ws.defs[t].name)
    }

    fn expr(&self, d: DefId, e: &Expr) -> String {
        match e {
            Expr::Int(v) => format!("{}n", v),
            Expr::Float(v) => crate::fmt::fmt_f64(*v),
            Expr::Str(s) => js_str(s),
            Expr::Var(id) => match self.bind(d, id.span, &id.name) {
                Binding::Local(s) => format!("s{}", s),
                Binding::Def(t) => self.defname(t),
                Binding::Broken => "undefined".to_string(),
            },
            Expr::FunRef(id) => match self.bind(d, id.span, &id.name) {
                Binding::Def(t) => self.defname(t),
                _ => "undefined".to_string(),
            },
            Expr::Lambda {
                lifted, captures, ..
            } => {
                // A closure lowers to a partial application of the lifted
                // definition, so the emitted code carries the same identity
                // the graph does. Always a closure, even with no captures,
                // because the VM tells a closure from a named reference.
                let target = match lifted {
                    Some(id) => match self.bind(d, id.span, &id.name) {
                        Binding::Def(t) => self.defname(t),
                        _ => "undefined".to_string(),
                    },
                    None => "undefined".to_string(),
                };
                let caught: Vec<String> = captures.iter().map(|c| self.slot(d, c)).collect();
                format!("$close({}, [{}])", target, caught.join(", "))
            }
            Expr::TimeCall { .. } => {
                "(()=>{throw new RigidError('temporal calls are VM-only in v14')})()"
                    .to_string()
            }
            Expr::Call { callee, args } => {
                let a: Vec<String> = args.iter().map(|x| self.expr(d, x)).collect();
                match self.bind(d, callee.span, &callee.name) {
                    Binding::Def(t) => format!("{}({})", self.defname(t), a.join(", ")),
                    _ => format!("{}({})", self.slot(d, callee), a.join(", ")),
                }
            }
            Expr::DynCall {
                targets,
                callee,
                args,
            } => {
                let set: Vec<String> = targets
                    .iter()
                    .filter_map(|t| match self.bind(d, t.span, &t.name) {
                        Binding::Def(x) => Some(self.defname(x)),
                        _ => None,
                    })
                    .collect();
                let a: Vec<String> = args.iter().map(|x| self.expr(d, x)).collect();
                format!(
                    "$dcall({}, [{}], [{}])",
                    self.expr(d, callee),
                    set.join(", "),
                    a.join(", ")
                )
            }
            Expr::TableDispatch { table, key, args } => {
                match self.bind(d, table.span, &table.name) {
                    Binding::Local(s) => format!("$index(s{}, {})", s, self.expr(d, key)),
                    Binding::Def(t) => match args {
                        None => format!("$tbl({}, {})", self.defname(t), self.expr(d, key)),
                        Some(a) => {
                            let xs: Vec<String> = a.iter().map(|x| self.expr(d, x)).collect();
                            format!(
                                "$tcall({}, {}, [{}])",
                                self.defname(t),
                                self.expr(d, key),
                                xs.join(", ")
                            )
                        }
                    },
                    Binding::Broken => "undefined".to_string(),
                }
            }
            Expr::Binop { op, l, r } => {
                let (a, b) = (self.expr(d, l), self.expr(d, r));
                use BinOp::*;
                match op {
                    Add => format!("$add({}, {})", a, b),
                    Sub => format!("$sub({}, {})", a, b),
                    Mul => format!("$mul({}, {})", a, b),
                    Div => format!("$div({}, {})", a, b),
                    Rem => format!("$rem({}, {})", a, b),
                    Eq => format!("$eq({}, {})", a, b),
                    Ne => format!("(1n - $eq({}, {}))", a, b),
                    Lt => format!("$lt({}, {})", a, b),
                    Gt => format!("$gt({}, {})", a, b),
                    Le => format!("$le({}, {})", a, b),
                    Ge => format!("$ge({}, {})", a, b),
                }
            }
            Expr::If { c, t, e: el } => format!(
                "($bool({}) ? {} : {})",
                self.expr(d, c),
                self.expr(d, t),
                self.expr(d, el)
            ),
            Expr::Neg(x) => format!("$neg({})", self.expr(d, x)),
            Expr::Print { arg, .. } => format!("$print({})", self.expr(d, arg)),
            Expr::Input { .. } => "$input()".to_string(),
            Expr::ListLit(xs) => format!(
                "[{}]",
                xs.iter().map(|x| self.expr(d, x)).collect::<Vec<_>>().join(", ")
            ),
            Expr::RecordLit(fs) => {
                // canonical (name-sorted) order, as the VM evaluates them
                let mut order: Vec<&(Ident, Expr)> = fs.iter().collect();
                order.sort_by(|a, b| a.0.name.cmp(&b.0.name));
                format!(
                    "$rec([{}], [{}])",
                    order.iter().map(|(n, _)| js_str(&n.name)).collect::<Vec<_>>().join(", "),
                    order.iter().map(|(_, v)| self.expr(d, v)).collect::<Vec<_>>().join(", ")
                )
            }
            Expr::Get { base, field } => {
                format!("$field({}, {})", self.expr(d, base), js_str(&field.name))
            }
            Expr::IndexE { base, key } => {
                format!("$index({}, {})", self.expr(d, base), self.expr(d, key))
            }
            Expr::Len(x) => format!("$len({})", self.expr(d, x)),
            Expr::Push(a, b) => format!("$push({}, {})", self.expr(d, a), self.expr(d, b)),
            Expr::StrConv(x) => format!("$str({})", self.expr(d, x)),
            Expr::IntConv(x) => format!("$int({})", self.expr(d, x)),
            Expr::FloatConv(x) => format!("$float({})", self.expr(d, x)),
            Expr::Substr(a, b, c) => format!(
                "$substr({}, {}, {})",
                self.expr(d, a),
                self.expr(d, b),
                self.expr(d, c)
            ),
            Expr::Chars(x) => format!("$chars({})", self.expr(d, x)),
            Expr::Join(a, b) => format!("$join({}, {})", self.expr(d, a), self.expr(d, b)),
            Expr::ReadFile { path, .. } => format!("$readFile({})", self.expr(d, path)),
            Expr::WriteFile { path, contents, .. } => format!(
                "$writeFile({}, {})",
                self.expr(d, path),
                self.expr(d, contents)
            ),
            Expr::Fail(x) => format!("$fail({})", self.expr(d, x)),
            Expr::Try(x) => format!("$try(() => {})", self.expr(d, x)),
        }
    }
}
