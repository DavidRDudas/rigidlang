//! JavaScript backend: lowers a resolved workspace to a single module.
//!
//! The emitted code must behave exactly as rigid's VM does — the same
//! values, the same errors, the same messages — because a program has one
//! meaning, not one per engine. `tools/difftest.sh` and the differential
//! tests in `tests/` hold it to that. Design rules:
//!   * Int is BigInt and Float is number. An integer result outside 64 bits
//!     is the same `integer overflow` error the VM raises.
//!   * Locals are named by slot, not by source name, and declared once at
//!     the top of the function: rigid's scope is flat per function, and a
//!     re-`let` of a name is a new slot.
//!   * Records are null-prototype objects and tables are Maps, so no key —
//!     `constructor`, `__proto__` — can reach JavaScript's own machinery.
//!   * A function value's identity is its content hash (`$h`). Equality, dyn
//!     membership and display go through it, never through a name.
//!   * Calls count against the VM's depth limit, with the VM's message.
//!   * Names are mangled from module path + definition name. The mangling is
//!     readable rather than injective, so `check` refuses a workspace where
//!     two definitions would land on one JavaScript name (E0213).
//!   * `fail`/`try` lower to throw/catch of a RigidError carrying a value.
//!   * Effects (`!io`) are erased: they are a compile-time discipline.

use crate::ast::*;
use crate::diag::{Diagnostic, Severity, E0213_TARGET};
use crate::resolve::{Binding, DefId, DefKind, Workspace};
use std::collections::HashMap;

pub struct Js<'a> {
    ws: &'a Workspace,
    out: String,
    /// def -> how many local slots it uses, parameters included
    slots: HashMap<DefId, u32>,
}

fn mangle(module_path: &str, name: &str) -> String {
    let mut m: String = module_path
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect::<String>()
        .trim_matches('_')
        .to_string();
    // a JavaScript identifier cannot start with a digit
    if m.is_empty() || m.starts_with(|c: char| c.is_ascii_digit()) {
        m.insert(0, 'm');
    }
    format!("{}__{}", m, name)
}

fn js_str(s: &str) -> String {
    serde_json::to_string(s).unwrap()
}

/// Definitions this target cannot represent. Mangling keeps names readable,
/// so it is not injective (`a-b.rg` and `a_b.rg` both become `a_b_rg`), and
/// two definitions on one name would silently become one function. The
/// build is refused instead.
pub fn check(ws: &Workspace) -> Vec<Diagnostic> {
    let mut seen: HashMap<String, DefId> = HashMap::new();
    let mut out = Vec::new();
    for d in 0..ws.defs.len() {
        let m = mangle(&ws.defs[d].module_path, &ws.defs[d].name);
        match seen.get(&m) {
            Some(&o) => out.push(Diagnostic::new(
                E0213_TARGET,
                Severity::Error,
                &ws.defs[d].module_path,
                None,
                format!(
                    "{}#{} and {}#{} would both be named `{}` in JavaScript; rename one of the modules",
                    ws.defs[o].module_path, ws.defs[o].name, ws.defs[d].module_path, ws.defs[d].name, m
                ),
            )),
            None => {
                seen.insert(m, d);
            }
        }
    }
    out
}

